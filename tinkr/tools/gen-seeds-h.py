#!/usr/bin/env python3
"""Generate seeds.h from skill YAML files.

Reads skills/**/*.yaml, groups `lowering: indirect_call` skills by
their `seed.header` sub-struct name, builds C function pointer types
from each skill's `signature`, and emits a single seeds.h with all
sub-structs plus the top-level `struct seeds` that owns one pointer
per sub-struct.

Skills with other lowerings (`syscall`, `objc_msgsend`) don't carry
function-pointer fields in the seed (they're inline-asm / message-send
patterns), so they don't appear in seeds.h.

Re-run after adding or removing skills.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tinkr_skills import (  # noqa: E402
    REPO_ROOT, SKILLS_DIR, SEEDS_H,
    iter_skills, parse_seed_access, portabilise_type, first_line,
)

OUT = SEEDS_H

PREAMBLE = """\
#ifndef TINKR_SEEDS_H
#define TINKR_SEEDS_H

/* AUTOGENERATED -- do not hand-edit.
 * Source of truth: skills/<platform>/<lib>/<function>.yaml
 * Regenerate:      tools/gen-seeds-h.py
 *
 * No <sys/types.h> dependency: skills using ssize_t / off_t are rendered
 * with explicit-width types (long / long long) so seeds.h works for
 * SDK-less cross-compiles (e.g. clang --target=arm64-apple-macos on a
 * Linux host without the macOS SDK installed).
 */

#include <stddef.h>

"""

POSTAMBLE = "#endif\n"


def render_param_list(params):
    if not params:
        return "void"
    parts = []
    for p in params:
        c_type = portabilise_type(p["c_type"].strip())
        name = p.get("name", "")
        parts.append(f"{c_type} {name}".strip() if name else c_type)
    return ", ".join(parts)


def main():
    structs = {}              # struct_name -> [(field, ret_c, params, doc)]
    seeds_field_of = {}       # struct_name -> seeds-level field name
    skill_count = 0
    skipped = 0

    for path, skill in iter_skills():
        if skill.get("lowering") != "indirect_call":
            skipped += 1
            continue

        seed = skill.get("seed") or {}
        struct_name = seed.get("header")
        field_name = seed.get("field")
        access = seed.get("access", "")

        if not (struct_name and field_name and access):
            print(f"[gen-seeds-h] {path.relative_to(REPO_ROOT)}: incomplete seed block", file=sys.stderr)
            continue

        try:
            seeds_field, parsed_field = parse_seed_access(access)
        except ValueError as e:
            print(f"[gen-seeds-h] {path.relative_to(REPO_ROOT)}: {e}", file=sys.stderr)
            continue
        if parsed_field != field_name:
            print(
                f"[gen-seeds-h] {path.relative_to(REPO_ROOT)}: "
                f"seed.field={field_name!r} does not match access tail {parsed_field!r}",
                file=sys.stderr,
            )
            continue

        prior_seeds_field = seeds_field_of.get(struct_name)
        if prior_seeds_field and prior_seeds_field != seeds_field:
            print(
                f"[gen-seeds-h] {path.relative_to(REPO_ROOT)}: "
                f"struct {struct_name} accessed as both {prior_seeds_field!r} and {seeds_field!r}",
                file=sys.stderr,
            )
            continue
        seeds_field_of[struct_name] = seeds_field

        doc = first_line(skill.get("description"))

        override = seed.get("type")
        if override:
            # Explicit type override (e.g. variadic functions like objc_msgSend
            # or NSLog where the typed function-pointer form is a footgun and
            # callers must cast before invoking).
            entry = ("override", field_name, override.strip(), doc)
        else:
            sig = skill["signature"]
            ret_c = portabilise_type(sig["return"]["c_type"].strip())
            params_c = render_param_list(sig.get("params", []))
            entry = ("fnptr", field_name, ret_c, params_c, doc)

        structs.setdefault(struct_name, []).append(entry)
        skill_count += 1

    out = PREAMBLE
    for struct_name in sorted(structs):
        fields = sorted(set(structs[struct_name]))
        out += f"struct {struct_name} {{\n"
        for entry in fields:
            kind = entry[0]
            if kind == "override":
                _, field, type_str, doc = entry
                if doc:
                    out += f"    /* {doc} */\n"
                out += f"    {type_str} {field};\n"
            else:
                _, field, ret_c, params, doc = entry
                if doc:
                    out += f"    /* {doc} */\n"
                out += f"    {ret_c} (*{field})({params});\n"
        out += "};\n\n"

    if structs:
        max_struct_len = max(len(s) for s in structs)
        out += "struct seeds {\n"
        for struct_name in sorted(structs):
            sf = seeds_field_of[struct_name]
            out += f"    struct {struct_name.ljust(max_struct_len)} *{sf};\n"
        out += "};\n\n"
    else:
        out += "struct seeds { int _empty; };\n\n"

    out += POSTAMBLE
    OUT.write_text(out)
    print(
        f"[gen-seeds-h] wrote {OUT.relative_to(REPO_ROOT)} "
        f"({len(structs)} sub-structs, {skill_count} indirect_call fields, {skipped} skills skipped)"
    )


if __name__ == "__main__":
    main()
